import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { guardOwnedTestDatabasePoolTeardownV1 } from './lib/owned-test-database-pool-teardown-v1.mjs';
const pool = new EventEmitter(), database = 'communications_currentness_controlled';
const guard = guardOwnedTestDatabasePoolTeardownV1(pool, database);
const error = Object.assign(new Error('controlled termination'), { code: '57P01' });
assert.throws(() => pool.emit('error', error, { database }), e => e === error, 'active phase preserves original error');
guard.beginOwnDrop();
assert.doesNotThrow(() => pool.emit('error', error, { connectionParameters: { database } }));
assert.throws(() => pool.emit('error', error, { database: 'different_database' }), e => e === error);
assert.throws(() => pool.emit('error', error), e => e === error);
const serialization = Object.assign(new Error('controlled serialization'), { code: '40001' });
assert.throws(() => pool.emit('error', serialization, { database }), e => e === serialization);
const ordinary = new Error('ordinary');
assert.throws(() => pool.emit('error', ordinary, { database }), e => e === ordinary);
const unowned = new EventEmitter(), missing = guardOwnedTestDatabasePoolTeardownV1(unowned, null);
assert.throws(() => missing.beginOwnDrop(), /OWNED_TEST_DATABASE_REQUIRED/);
assert.throws(() => unowned.emit('error', error, { database }), e => e === error);
console.log('PASS owned test DB teardown: one bounded late57P01; seven active/foreign/missing/40001/ordinary/unowned denials preserve original errors; no SQL/retry');
